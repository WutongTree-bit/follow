// Regenerate icons and outlined wordmarks: node scripts/brand.ts <@fontsource/noto-sans-sc package directory>
import { readFileSync, writeFileSync } from "node:fs";
import path from "node:path";
import sharp from "sharp";
import opentype from "opentype.js";
import { SITE } from "@aihot/site";
import { BRAND_MARK } from "../site/brand/mark.ts";

const pkg = process.argv[2];
if (!pkg) throw new Error("usage: node scripts/brand.ts <noto-sans-sc package dir>");

const target = new URL("../site/brand/", import.meta.url);
const light = { accent: "#176b75", hot: "#d6452f", ink: "#0e191b" };
const dark = { accent: "#2ce2e8", hot: "#ff6a5a", ink: "#e6eded" };

function mark(colors: typeof light): string {
  return `<path d="${BRAND_MARK.ring}" fill="none" stroke="${colors.accent}" stroke-width="28" stroke-linecap="round"/>`
    + `<circle cx="${BRAND_MARK.dot.cx}" cy="${BRAND_MARK.dot.cy}" r="${BRAND_MARK.dot.r}" fill="${colors.hot}"/>`
    + BRAND_MARK.bars.map((b, i) => `<rect x="${b.x}" y="${b.y}" width="${b.width}" height="${b.height}" rx="${b.rx}" fill="${i === 2 ? colors.hot : colors.accent}"/>`).join("");
}

const escapeXml = (s: string) => s.replace(/[&<>"']/g, (c) => ({ "&": "&amp;", "<": "&lt;", ">": "&gt;", '"': "&quot;", "'": "&apos;" })[c]!);
function icon(square = false): string {
  return `<svg xmlns="http://www.w3.org/2000/svg" viewBox="${BRAND_MARK.viewBox}"><title>${escapeXml(SITE.name)}</title>`
    + `<rect width="512" height="512" rx="${square ? 0 : 112}" fill="#13191c"/>${mark(dark)}</svg>\n`;
}

writeFileSync(new URL("logo.svg", target), icon());
for (const [name, size, square] of [
  ["icon.png", 512, false], ["icon-192.png", 192, false], ["apple-icon.png", 180, true],
] as const) {
  writeFileSync(new URL(name, target), await sharp(Buffer.from(icon(square))).resize(size, size).png().toBuffer());
}

const css = readFileSync(path.join(pkg, "900.css"), "utf8");
const faces = [...css.matchAll(/url\(\.\/files\/([\w-]+)\.woff2\)[^;]*;\s*unicode-range: ([^;]+);/g)].map((m) => ({
  file: `${m[1]}.woff`,
  ranges: m[2]!.split(",").map((r) => r.trim().replace("U+", "").split("-").map((h) => parseInt(h, 16))),
}));
const fonts = new Map<string, opentype.Font>();
function fontFor(ch: string): opentype.Font {
  const cp = ch.codePointAt(0)!;
  const face = faces.find((f) => f.ranges.some(([a, b]) => cp >= a! && cp <= (b ?? a!)));
  if (!face) throw new Error(`no font slice holds ${ch}`);
  if (!fonts.has(face.file)) {
    const buf = readFileSync(path.join(pkg, "files", face.file));
    fonts.set(face.file, opentype.parse(buf.buffer.slice(buf.byteOffset, buf.byteOffset + buf.byteLength)));
  }
  return fonts.get(face.file)!;
}

const chars = [...SITE.name];
const boxes = chars.map((ch) => fontFor(ch).getPath(ch, 0, 0, 1000).getBoundingBox());
const top = Math.min(...boxes.map((b) => b.y1));
const bottom = Math.max(...boxes.map((b) => b.y2));
const size = 1000 * 58 / (bottom - top);
const baseline = 50 - (top + bottom) / 2 * size / 1000;
let x = 106;
const glyphs = chars.map((ch, i) => {
  const box = boxes[i]!;
  const origin = x - box.x1 * size / 1000;
  const data = fontFor(ch).getPath(ch, origin, baseline, size).toPathData(1);
  x += (box.x2 - box.x1) * size / 1000 + 5;
  return data;
}).join(" ");

for (const [name, colors] of [["wordmark.svg", light], ["wordmark-dark.svg", dark]] as const) {
  writeFileSync(new URL(name, target),
    `<!-- Generated by scripts/brand.ts. Noto Sans SC Black (SIL OFL 1.1). -->\n`
    + `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 ${Math.ceil(x)} 100"><title>${escapeXml(SITE.name)}</title>`
    + `<g transform="translate(-16.8 -16.8) scale(.261)">${mark(colors)}</g><path d="${glyphs}" fill="${colors.ink}"/></svg>\n`);
}

const images = await Promise.all([16, 32, 48].map(async (size) => ({
  size, data: await sharp(Buffer.from(icon())).resize(size, size).png().toBuffer(),
})));
const header = Buffer.alloc(6);
header.writeUInt16LE(1, 2);
header.writeUInt16LE(images.length, 4);
let offset = 6 + 16 * images.length;
const entries = images.map(({ size, data }) => {
  const entry = Buffer.alloc(16);
  entry.writeUInt8(size, 0);
  entry.writeUInt8(size, 1);
  entry.writeUInt16LE(1, 4);
  entry.writeUInt16LE(32, 6);
  entry.writeUInt32LE(data.length, 8);
  entry.writeUInt32LE(offset, 12);
  offset += data.length;
  return entry;
});
writeFileSync(new URL("favicon.ico", target), Buffer.concat([header, ...entries, ...images.map((im) => im.data)]));
console.log(`Generated icons and wordmarks for ${SITE.name}`);
